// ---------------- behavioral kernels ----------------

/// Dispatch kernel: suggest best zone for a car class.
/// Score = free stalls, preferring zones that admit the class; None if none admit.
pub fn suggest_zone(
    zones: &[(ZoneId, String, u32, u32, Vec<VehicleClass>)],
    class: VehicleClass,
) -> Option<ZoneId> {
    zones
        .iter()
        .filter(|(_, _, cap, occ, allowed)| allowed.contains(&class) && occ < cap)
        .max_by_key(|(_, _, cap, occ, _)| cap - occ)
        .map(|(id, _, _, _, _)| *id)
}

/// Dispatch kernel: ETA minutes from distance (m) and speed (km/h). Fail-closed on bad input.
pub fn eta_minutes(dist_m: f64, speed_kmh: f64) -> Result<f64, String> {
    if dist_m < 0.0 {
        return Err("negative distance".into());
    }
    if speed_kmh <= 0.0 {
        return Err("speed must be positive".into());
    }
    Ok(dist_m / 1000.0 / speed_kmh * 60.0)
}

/// Tracking kernel: validate a GPS ping. Returns normalized (lat, lon, ts_ms) or reason.
pub fn validate_ping(lat: f64, lon: f64, ts_ms: u64, now_ms: u64) -> Result<(f64, f64, u64), String> {
    if !(-90.0..=90.0).contains(&lat) || !(-180.0..=180.0).contains(&lon) {
        return Err("coordinates out of range".into());
    }
    if ts_ms > now_ms + 60_000 {
        return Err("timestamp from the future".into());
    }
    if now_ms.saturating_sub(ts_ms) > 7 * 24 * 3600 * 1000 {
        return Err("ping older than 7 days".into());
    }
    Ok((lat, lon, ts_ms))
}

/// Tracking kernel: stale if older than threshold.
pub fn is_stale(ts_ms: u64, now_ms: u64, threshold_ms: u64) -> bool {
    now_ms.saturating_sub(ts_ms) > threshold_ms
}

/// Tracking kernel: speed km/h between two pings. None if timestamps invalid.
pub fn speed_kmh(
    lat1: f64,
    lon1: f64,
    t1: u64,
    lat2: f64,
    lon2: f64,
    t2: u64,
) -> Option<f64> {
    if t2 <= t1 {
        return None;
    }
    let dlat = (lat2 - lat1).to_radians();
    let dlon = (lon2 - lon1).to_radians();
    let a = (dlat / 2.0).sin().powi(2)
        + lat1.to_radians().cos() * lat2.to_radians().cos() * (dlon / 2.0).sin().powi(2);
    let dist_m = 2.0 * 6_371_008.8 * a.sqrt().asin();
    let hours = (t2 - t1) as f64 / 3_600_000.0;
    Some(dist_m / 1000.0 / hours)
}

/// Tracking kernel: impossible-speed check (faster than 200 km/h = bad ping).
pub fn is_impossible_speed(kmh: f64) -> bool {
    kmh > 200.0
}
