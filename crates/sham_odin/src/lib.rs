#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Batch {
    Dispatch,
    Tracking,
    Comms,
    Reporting,
    Admin,
    FieldOps,
    Analytics,
    Integrations,
}
impl Batch {
    pub fn prefix(self) -> &'static str {
        match self {
            Batch::Dispatch => "ODIN-DIS",
            Batch::Tracking => "ODIN-TRK",
            Batch::Comms => "ODIN-COM",
            Batch::Reporting => "ODIN-REP",
            Batch::Admin => "ODIN-ADM",
            Batch::FieldOps => "ODIN-FLD",
            Batch::Analytics => "ODIN-ANL",
            Batch::Integrations => "ODIN-INT",
        }
    }
    pub fn name(self) -> &'static str {
        match self {
            Batch::Dispatch => "dispatch",
            Batch::Tracking => "tracking",
            Batch::Comms => "comms",
            Batch::Reporting => "reporting",
            Batch::Admin => "admin",
            Batch::FieldOps => "field-ops",
            Batch::Analytics => "analytics",
            Batch::Integrations => "integrations",
        }
    }
    pub fn expected_count(self) -> usize {
        match self {
            Batch::Integrations => 21,
            _ => 25,
        }
    }
}

#[derive(Clone, Debug)]
pub struct Feature {
    pub id: String,
    pub name: &'static str,
    pub batch: Batch,
    pub desc: &'static str,
}

/// All 196 features, in batch order. Generated by macro below for compactness.
macro_rules! batch {
    ($b:expr, [ $( ($n:literal, $d:literal) ),* $(,)? ]) => {{
        let mut v: Vec<Feature> = Vec::new();
        let mut i = 0usize;
        $(
            i += 1;
            v.push(Feature {
                id: format!("{}-{:03}", $b.prefix(), i),
                name: $n,
                batch: $b,
                desc: $d,
            });
        )*
        v
    }};
}

pub fn all_features() -> Vec<Feature> {
    let mut all = Vec::with_capacity(196);
    all.extend(dispatch_features());
    all.extend(tracking_features());
    all.extend(comms_features());
    all.extend(reporting_features());
    all.extend(admin_features());
    all.extend(fieldops_features());
    all.extend(analytics_features());
    all.extend(integrations_features());
    all
}

pub struct Registry {
    by_id: HashMap<String, Feature>,
}
impl Registry {
    pub fn load() -> Self {
        let mut by_id = HashMap::new();
        for f in all_features() {
            by_id.insert(f.id.clone(), f);
        }
        Self { by_id }
    }
    pub fn get(&self, id: &str) -> Option<&Feature> {
        self.by_id.get(id)
    }
    pub fn len(&self) -> usize {
        self.by_id.len()
    }
    pub fn batch_count(&self, b: Batch) -> usize {
        self.by_id.values().filter(|f| f.batch == b).count()
    }
    /// Fail-closed: ids must match batch prefix and be unique.
    pub fn check_integrity(&self) -> Result<(), String> {
        for f in self.by_id.values() {
            let want = format!("{}-", f.batch.prefix());
            if !f.id.starts_with(&want) {
                return Err(format!("feature id {} mismatches batch {}", f.id, f.batch.name()));
            }
        }
        Ok(())
    }
}

